import numpy as np

customer_sales = df.groupby('Customer Name')['Sales'].sum().reset_index()
customer_sales = customer_sales.sort_values(by='Sales', ascending=False, ignore_index=True)

total_sales = customer_sales['Sales'].sum()
customer_sales['Cumulative_Sales_Pct'] = customer_sales['Sales'].cumsum() / total_sales * 100

total_customers_count = len(customer_sales)
customer_sales['Customer_Percentile'] = (customer_sales.index + 1) / total_customers_count * 100

top_20_count = int(total_customers_count * 0.2)
top_20_sales_share = customer_sales.loc[top_20_count - 1, 'Cumulative_Sales_Pct']

print(f"Pareto Check:")
print(f"Total Customers: {total_customers_count}")
print(f"Top 20% of Customers ({top_20_count}) account for {top_20_sales_share:.2f}% of total Sales.\n")

# 4. Plotting the normalized cumulative curve (Lorenz Curve style)
plt.figure(figsize=(10, 6))
plt.plot(customer_sales['Customer_Percentile'], customer_sales['Cumulative_Sales_Pct'], color='blue', lw=2.5, label='Cumulative Sales %')

# Mark the 20% / 80% intersection
plt.axvline(x=20, color='red', linestyle='--', alpha=0.7, label='Top 20% Customers')
plt.axhline(y=top_20_sales_share, color='green', linestyle='--', alpha=0.7, label=f'{top_20_sales_share:.1f}% Sales')

plt.title('Pareto Analysis: Cumulative Sales by Customer %', fontsize=14, fontweight='bold')
plt.xlabel('% of Customers (Sorted by Sales)', fontsize=12)
plt.ylabel('% of Total Sales', fontsize=12)
plt.xlim(0, 100)
plt.ylim(0, 105)
plt.grid(True, linestyle=':', alpha=0.6)
plt.legend(loc='lower right')
plt.tight_layout()
plt.show()

"""Based on the analysis, both california and new york has the highest sales and also profitability is is high. Would definitely prioritize in these states. On the other hands states like Texas, Ohio, Pennsylvania, iilinois, North Carolina,colarado, Tennesse, Arizona, Florida Oregon, the profit is negative. It is worth looking into what's going on here, customer sales, products, discounts. I will further analyze here to see why the profit is negative. One more interesting thing to notice is top 20% of customer overall generate 80% of profit which is also something to look into further.

The 80/20 Rule Check:
* Profits are heavily concentrated:  Only **20% of your customers make up over 81% of your profits**. This means a small group of VIPs are keeping the lights on. They need high-touch support or loyalty programs.
* **Sales are much more spread out:** Interestingly, that same top 20% of customers only generate **48% of total sales**. This tells us that many of your lower-profit customers are buying high volumes of cheap or heavily discounted items.

#### 2. Why are Texas, Ohio, PA, and Illinois losing money?
* **Discounting is likely out of control:** Look at the average discounts in these states. If salespeople are giving away 50-70% off to hit sales targets, it completely kills the profit margins.
* **Shipping costs:** These states cover huge geographic areas. Check if high freight/shipping costs are eating up the margins on bulky items.

#### 3. What to do next:
* **Keep California and New York happy:** Since they are your goldmines, double down on marketing and keep inventory stocked there.
* **Fix the bleeders, don't run away:** Instead of stopping sales in places like Texas, try capping maximum discounts at 15-20% and set a minimum order size for free shipping to see if they turn profitable.
"""

# Let's investigate the bleeding states: Texas, Ohio, Pennsylvania, Illinois
loss_states = ['Texas', 'Ohio', 'Pennsylvania', 'Illinois']
profit_states = ['California', 'New York']

# Calculate average discount and profit margin in loss states vs profit states
print("=== Discount & Profit Margin Comparison ===")
for group_name, states in [("Bleeding States (TX, OH, PA, IL)", loss_states), ("Profitable States (CA, NY)", profit_states)]:
    sub_df = df[df['State'].isin(states)]
    avg_discount = sub_df['Discount'].mean() * 100
    total_sales = sub_df['Sales'].sum()
    total_profit = sub_df['Profit'].sum()
    margin = (total_profit / total_sales) * 100
    print(f"{group_name}:")
    print(f"  Average Discount: {avg_discount:.1f}%")
    print(f"  Profit Margin: {margin:.1f}%")

print("\n=== Top Loss-Making Sub-Categories in Bleeding States ===")
loss_subcats = df[df['State'].isin(loss_states)].groupby('Sub-Category')[['Sales', 'Profit', 'Discount']].agg({'Sales':'sum', 'Profit':'sum', 'Discount':'mean'}).reset_index()
loss_subcats['Discount %'] = loss_subcats['Discount'] * 100
loss_subcats = loss_subcats.sort_values(by='Profit').head(5)
